/**
 * Watermarks and compresses the container/shipment photos used by the export
 * section.
 *
 *   node scripts/optimize-export.mjs
 *
 * Same treatment as the warehouse set: originals stay outside public/ so the
 * un-watermarked files are never served, and the output is WebP at a sane size.
 * Writes src/components/site/exportPhotos.ts with blur placeholders.
 */
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";
import { stamp } from "./lib/watermark.mjs";

const ROOT = process.cwd();
const SRC_DIR = path.join(ROOT, "assets", "export-src");
const OUT_DIR = path.join(ROOT, "public", "export");
const MANIFEST = path.join(ROOT, "src", "components", "site", "exportPhotos.ts");

const PHOTOS = [
  {
    source: "export-1.jpeg",
    slug: "export-shipment-1",
    alt: "Cartons of Suzuki Genuine Parts packed for an export shipment",
  },
  {
    source: "export-2.jpeg",
    slug: "export-shipment-2",
    alt: "Export cartons stacked and strapped ahead of container loading",
  },
  {
    source: "export-3.jpeg",
    slug: "export-shipment-3",
    alt: "Palletised OEM auto parts prepared for international freight",
  },
  {
    source: "export-4.jpeg",
    slug: "export-shipment-4",
    alt: "Sealed export cartons of Suzuki spare parts awaiting dispatch",
  },
];

const LONG_EDGE = 1400;

async function blurPlaceholder(file) {
  const buf = await sharp(path.join(SRC_DIR, file))
    .rotate()
    .resize(20, 20, { fit: "inside" })
    .webp({ quality: 40 })
    .toBuffer();
  return `data:image/webp;base64,${buf.toString("base64")}`;
}

async function main() {
  const entries = [];

  for (const { source, slug, alt } of PHOTOS) {
    const base = sharp(path.join(SRC_DIR, source)).rotate();
    const meta = await base.metadata();
    const landscape = meta.width >= meta.height;

    const info = await (
      await stamp(
        sharp(path.join(SRC_DIR, source))
          .rotate()
          .resize(landscape ? LONG_EDGE : null, landscape ? null : LONG_EDGE, {
            withoutEnlargement: true,
          }),
      )
    )
      .webp({ quality: 80, effort: 5 })
      .toFile(path.join(OUT_DIR, `${slug}.webp`));

    entries.push({
      src: `/export/${slug}.webp`,
      alt,
      width: info.width,
      height: info.height,
      blurDataURL: await blurPlaceholder(source),
    });

    console.log(
      `${source.padEnd(15)} -> ${slug}.webp ${info.width}x${info.height} ` +
        `(${(info.size / 1024).toFixed(0)} KB)`,
    );
  }

  const ts = `// AUTO-GENERATED by scripts/optimize-export.mjs — do not edit by hand.
// Run \`npm run images:export\` after adding or replacing photos.

export type ExportPhoto = {
  src: string;
  alt: string;
  width: number;
  height: number;
  /** Tiny inline WebP used as the next/image blur placeholder. */
  blurDataURL: string;
};

export const EXPORT_PHOTOS: ExportPhoto[] = ${JSON.stringify(entries, null, 2)};
`;

  await fs.writeFile(MANIFEST, ts, "utf8");
  console.log(`\nWrote ${path.relative(ROOT, MANIFEST)} (${entries.length} photos)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
