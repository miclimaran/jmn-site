/**
 * Bakes the Open Graph background photo into a base64 module.
 *
 *   node scripts/make-og-bg.mjs
 *
 * Why a baked-in data URI rather than reading public/ at request time:
 * `opengraph-image.tsx` runs on the server, and Satori needs the raw bytes. A
 * runtime fetch or fs read is one more thing that can fail in a deploy, and if
 * it fails the site has no preview image at all. This costs a chunk of
 * server-only bundle and nothing at request time.
 *
 * JPEG, not WebP — Satori's decoder handles JPEG/PNG reliably, WebP it does not.
 */
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
// The un-watermarked original: the OG card carries its own JMN branding, so a
// second watermark underneath it would only fight the text.
const SOURCE = path.join(ROOT, "assets", "warehouse-src", "JMN12.jpeg");
const OUT = path.join(ROOT, "src", "app", "ogBackground.ts");

const WIDTH = 1200;
const HEIGHT = 630;

async function main() {
  const buf = await sharp(SOURCE)
    .rotate()
    .resize(WIDTH, HEIGHT, { fit: "cover", position: sharp.strategy.attention })
    // Darkened hard at source. The card is read at thumbnail size in a feed,
    // so the photo only needs to register as "a wall of stock" behind the type;
    // any more brightness and the headline stops being legible.
    .modulate({ brightness: 0.78, saturation: 0.88 })
    .jpeg({ quality: 72, mozjpeg: true })
    .toBuffer();

  const dataUri = `data:image/jpeg;base64,${buf.toString("base64")}`;

  await fs.writeFile(
    OUT,
    `// AUTO-GENERATED by scripts/make-og-bg.mjs — do not edit by hand.
// Run \`npm run images:og\` after changing the source photo.
// Server-only: imported by app/opengraph-image.tsx, never by client code.

export const OG_BACKGROUND = "${dataUri}";
`,
    "utf8",
  );

  console.log(
    `${path.basename(SOURCE)} -> ${path.relative(ROOT, OUT)} ` +
      `${WIDTH}x${HEIGHT} (${(buf.length / 1024).toFixed(0)} KB source, ` +
      `${(dataUri.length / 1024).toFixed(0)} KB base64)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
