"use client";

import * as React from "react";
import Image from "next/image";
import Section from "@/components/site/sections/Section";
import { useT } from "@/components/site/Lang";
import { useHomeCopy } from "@/components/site/useHomeCopy";
import { withMissing } from "@/components/site/ui/Missing";
import { WAREHOUSE_PHOTOS } from "@/components/site/warehousePhotos";
import { EXPORT_PHOTOS } from "@/components/site/exportPhotos";

type Plate = {
  src: string;
  alt: string;
  width: number;
  height: number;
  blurDataURL: string;
  /** Lang key, when the photo has a translated caption. */
  captionKey?: string;
};

const PLATES: Plate[] = [
  ...WAREHOUSE_PHOTOS.map((photo) => ({
    src: photo.src,
    alt: photo.alt,
    width: photo.width,
    height: photo.height,
    blurDataURL: photo.blurDataURL,
    captionKey: photo.captionKey,
  })),
  // exportPhotos.ts is generated by a script and carries English alt text
  // only, so the caption keys are attached here by position.
  ...EXPORT_PHOTOS.map((photo, i) => ({
    ...photo,
    captionKey: `ex_cap_${i + 1}`,
  })),
];

/**
 * Stock and packing photographs.
 *
 * Every image is one of ours, taken in the Jakarta warehouse — no stock
 * photography and nothing generated. The grid is plain and the lightbox is
 * hand-rolled rather than a dialog component, because all it needs is an
 * overlay, arrow keys and Escape.
 */
export default function StockProof() {
  const copy = useHomeCopy();
  const t = useT();
  const [open, setOpen] = React.useState<number | null>(null);

  const caption = (plate: Plate) =>
    plate.captionKey ? t(plate.captionKey as Parameters<typeof t>[0]) : plate.alt;

  React.useEffect(() => {
    if (open === null) return;

    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") setOpen(null);
      if (event.key === "ArrowRight")
        setOpen((i) => ((i ?? 0) + 1) % PLATES.length);
      if (event.key === "ArrowLeft")
        setOpen((i) => ((i ?? 0) - 1 + PLATES.length) % PLATES.length);
    };

    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open]);

  const active = open === null ? null : PLATES[open];

  return (
    <Section
      id="stock"
      index="04"
      title={copy.proof.title}
      lead={copy.proof.lead}
      tone="tint"
    >
      <ul className="grid grid-cols-2 gap-px bg-line sm:grid-cols-3 lg:grid-cols-5">
        {PLATES.map((plate, i) => (
          <li key={plate.src} className="bg-paper">
            <button
              type="button"
              onClick={() => setOpen(i)}
              className="group block w-full text-start"
              aria-label={caption(plate)}
            >
              <span className="relative block aspect-square overflow-hidden bg-paper-3">
                <Image
                  src={plate.src}
                  alt={plate.alt}
                  fill
                  sizes="(max-width: 640px) 50vw, (max-width: 1024px) 33vw, 20vw"
                  placeholder="blur"
                  blurDataURL={plate.blurDataURL}
                  className="object-cover transition-opacity duration-150 group-hover:opacity-85"
                />
              </span>
              <span className="block px-2 py-2 text-[0.6875rem] leading-snug text-ink-2">
                {caption(plate)}
              </span>
            </button>
          </li>
        ))}
      </ul>

      <p className="mt-4 text-xs text-ink-3">{copy.proof.note}</p>

      <div className="mt-10 hair bg-paper p-5 lg:max-w-2xl">
        <h3 className="text-[0.9375rem] font-semibold">{copy.proof.docsTitle}</h3>
        <p className="mt-2 text-sm leading-relaxed text-ink-2">
          {withMissing(copy.proof.docsBody)}
        </p>
      </div>

      {active && (
        <div
          role="dialog"
          aria-modal="true"
          aria-label={caption(active)}
          onClick={() => setOpen(null)}
          className="fixed inset-0 z-[60] flex flex-col items-center justify-center bg-ink/92 p-4"
        >
          <div
            className="relative max-h-[80vh] w-full max-w-4xl"
            onClick={(event) => event.stopPropagation()}
          >
            <Image
              src={active.src}
              alt={active.alt}
              width={active.width}
              height={active.height}
              sizes="90vw"
              className="mx-auto max-h-[80vh] w-auto object-contain"
            />
          </div>
          <div className="mt-4 flex w-full max-w-4xl items-baseline justify-between gap-6 text-xs text-paper-3">
            <span>{caption(active)}</span>
            <span className="pn">
              {(open ?? 0) + 1} / {PLATES.length}
            </span>
          </div>
          <button
            type="button"
            onClick={() => setOpen(null)}
            className="mt-4 border border-paper-3/40 px-4 py-2 text-xs text-paper hover:bg-paper/10"
          >
            {t("wh_close")}
          </button>
        </div>
      )}
    </Section>
  );
}
